import 'dart:io';

import 'package:test/test.dart';
import 'package:path/path.dart' as p;

import '../../src/architecture.dart';

void main() {
  late Directory root;
  setUp(() {
    root = Directory.systemTemp.createTempSync('architecture-');
    File(p.join(root.path, 'pubspec.yaml'))
        .writeAsStringSync('workspace: [a, b]\n');
    for (final name in ['a', 'b']) {
      Directory(p.join(root.path, name, 'lib', 'src'))
          .createSync(recursive: true);
      File(p.join(root.path, name, 'pubspec.yaml'))
          .writeAsStringSync('name: $name\n');
    }
  });
  tearDown(() => root.deleteSync(recursive: true));

  void source(String path, String content) {
    final file = File(p.join(root.path, path));
    file.parent.createSync(recursive: true);
    file.writeAsStringSync(content);
  }

  void application(Map<String, String> files) {
    source('pubspec.yaml', 'workspace: [app]\n');
    source('app/pubspec.yaml', 'name: scrcpy_connect\n');
    for (final entry in files.entries) {
      source('app/lib/${entry.key}', entry.value);
    }
  }

  List<String> check({Map<String, Set<String>>? dependencies}) =>
      checkArchitecture(
        root,
        allowedDependencies: dependencies ?? {'a': {}, 'b': {}},
      );

  test('检测多文件循环但不会把正常菱形依赖或 part 当作循环', () {
    source('a/lib/a.dart', "import 'src/left.dart'; import 'src/right.dart';");
    source('a/lib/src/left.dart', "import 'shared.dart';");
    source('a/lib/src/right.dart', "import 'shared.dart';");
    source('a/lib/src/shared.dart', "part 'shared.g.dart';");
    source('a/lib/src/shared.g.dart', "part of 'shared.dart';");
    expect(check(), isEmpty);
    source('a/lib/src/shared.dart', "export '../a.dart';");
    final result = check();
    expect(result, hasLength(1));
    expect(result.single, contains('模块依赖环'));
    expect(result.single, contains('a/lib/src/shared.dart'));
  });

  test('条件导入同样核验直接依赖与私有实现访问', () {
    source(
      'a/lib/a.dart',
      "import 'local.dart' if (dart.library.io) 'package:b/src/private.dart';",
    );
    source('a/lib/local.dart', '// import "package:b/b.dart";');
    final result = check(
      dependencies: {
        'a': {'b'},
        'b': {},
      },
    );
    expect(result, hasLength(2));
    expect(result, contains(contains('未声明的直接依赖 b')));
    expect(result, contains(contains('跨包访问私有实现')));
  });

  test('依赖清单即使暂时未使用也不能逆转能力分层', () {
    source('a/pubspec.yaml', 'name: a\ndependencies:\n  b:\n    path: ../b\n');
    source('a/lib/a.dart', "export 'package:b/b.dart';");
    expect(check(), [contains('a 不允许依赖 b')]);
    expect(
      check(
        dependencies: {
          'a': {'b'},
          'b': {},
        },
      ),
      isEmpty,
    );
  });

  test('工作区不能遗留未声明的本地业务包', () {
    source('packages/hidden/pubspec.yaml', 'name: hidden\n');
    expect(check(), [contains('未纳入工作区的本地包')]);
  });

  test('文件与媒体业务不能经页面倒置依赖', () {
    application({
      'files/catalog/catalog.dart': "import '../../pages/browser.dart';",
      'pages/browser.dart': '// 页面',
    });
    expect(check(), [contains('应用业务模块不得依赖界面或路由')]);
  });

  test('相对路径不能绕过包的私有接口', () {
    source('a/lib/a.dart', "import '../../b/lib/src/private.dart';");
    expect(check(), [contains('相对导入越过包的 lib 目录')]);
  });

  test('排除带生成声明的库但仍核验其手写调用方', () {
    source('a/lib/a.dart', "import 'a.g.dart';");
    source(
      'a/lib/a.g.dart',
      "// GENERATED CODE - DO NOT MODIFY BY HAND\nimport 'a.dart';",
    );
    expect(check(), isEmpty);
    source('a/lib/a.g.dart', "import 'a.dart';");
    expect(check(), [contains('模块依赖环')]);
  });

  test('路由只豁免页面注册，不豁免经业务模块返回路由的依赖环', () {
    application({
      'router/app_router.dart': "import '../pages/home_page.dart';",
      'pages/home_page.dart': "import '../router/navigation.dart';",
      'router/navigation.dart': "import 'app_router.dart';",
    });
    expect(check(), isEmpty);
    source(
      'app/lib/router/app_router.dart',
      "import '../pages/home_page.dart'; import '../connection/validation.dart';",
    );
    source(
      'app/lib/connection/validation.dart',
      "import '../router/navigation.dart';",
    );
    expect(check(), [contains('应用业务模块不得依赖界面或路由'), contains('模块依赖环')]);
  });

  test('路由注册豁免不能掩盖应用编排依赖页面', () {
    application({
      'router/app_router.dart': "import '../pages/home_page.dart';",
      'pages/home_page.dart': "import '../application/controller.dart';",
      'application/controller.dart': "import '../router/app_router.dart';",
    });
    expect(check(), [contains('应用业务模块不得依赖界面或路由')]);
  });

  test('应用生成文件豁免不能容纳 FRB 产物或 Rust 源码', () {
    application({
      'native/binding.dart':
          '// This file is automatically generated, so please do not edit it.\n'
          '// @generated by `flutter_rust_bridge`@ 2.13.0.\n',
      'native/execution.rs': '// 原生实现应归能力包',
      'main.dart': "import 'local.dart' if (dart.library.io) 'package:flutter_rust_bridge/flutter_rust_bridge.dart';",
      'local.dart': '// Dart 能力入口',
    });
    source(
      'app/pubspec.yaml',
      'name: scrcpy_connect\ndependencies:\n  flutter_rust_bridge: 2.13.0\n',
    );
    expect(check(), [
      contains('应用不得直接导入 FRB'),
      contains('FRB 生成物必须由能力包维护'),
      contains('应用不得包含 Rust 源码'),
      contains('应用不得直接依赖 FRB'),
    ]);
  });

  test('应用测试、hook、平台目录及开发依赖也不能绕过 FRB 边界', () {
    application({'main.dart': '// 应用入口'});
    source(
      'app/test/bridge_test.dart',
      "export 'package:flutter_rust_bridge/flutter_rust_bridge.dart';",
    );
    source(
      'app/hook/frb_generated.dart',
      '// GENERATED CODE - DO NOT MODIFY BY HAND',
    );
    source('app/android/src/implementation.rs', '// Rust 必须归能力包');
    source('app/flutter_rust_bridge.yaml', 'rust_root: rust\n');
    source(
      'app/pubspec.yaml',
      'name: scrcpy_connect\ndev_dependencies:\n  flutter_rust_bridge: any\n',
    );
    // 只忽略实际缓存子树；其他目录的源码都要检查。
    source('app/build/dependency/frb_generated.dart', '// 由构建工具管理');
    expect(check(), [
      contains('应用不得包含 Rust 源码'),
      contains('FRB 配置必须位于工作区顶层'),
      contains('FRB 生成物必须由能力包维护'),
      contains('应用不得直接依赖 FRB'),
      contains('应用不得直接导入 FRB'),
    ]);
  });

  test('源码内与缓存同名的目录仍然检查应用边界', () {
    application({'main.dart': '// 应用入口'});
    const generated = [
      'lib/build/frb_generated.dart',
      'hook/Pods/frb_generated.dart',
      'android/app/src/main/build/frb_generated.dart',
    ];
    const rust = [
      'test/ephemeral/x.rs',
      'lib/.dart_tool/x.rs',
      'test/.gradle/x.rs',
      'hook/.cxx/x.rs',
      'lib/.symlinks/x.rs',
      'test/.plugin_symlinks/x.rs',
    ];
    for (final path in generated) {
      source('app/$path', '// 生成物不能藏在手写源码目录');
    }
    for (final path in rust) {
      source('app/$path', '// Rust 源码不能藏在同名目录');
    }
    expect(
      check(),
      [
        ...generated.map((path) => 'app/$path: FRB 生成物必须由能力包维护'),
        ...rust.map((path) => 'app/$path: 应用不得包含 Rust 源码'),
      ]..sort(),
    );
  });

  test('明确的应用与平台工具缓存子树不作为源输入检查', () {
    application({'main.dart': '// 应用入口'});
    for (final path in [
      'build',
      '.dart_tool',
      'android/.gradle',
      'android/.kotlin',
      'android/.cxx',
      'android/app/.cxx',
      'android/build',
      'android/app/build',
      'ios/Pods',
      'ios/.symlinks',
      'ios/Flutter/ephemeral',
      'macos/Pods',
      'macos/.symlinks',
      'macos/Flutter/ephemeral',
      'linux/flutter/ephemeral',
      'windows/flutter/ephemeral',
    ]) {
      source('app/$path/dependency/frb_generated.dart', '// 受控工具产物');
      source('app/$path/dependency/x.rs', '// 受控依赖源码');
    }
    expect(check(), isEmpty);
  });
}
