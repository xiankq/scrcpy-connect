import 'dart:io';

import 'package:analyzer/dart/ast/ast.dart';
import 'package:analyzer/dart/analysis/utilities.dart';
import 'package:path/path.dart' as p;
import 'package:yaml/yaml.dart';

// 只有可独立复用的能力拥有包；产品规则在应用的职责模块内组合。
const applicationLayers = {
  'bootstrap',
  'models',
  'stores',
  'services',
  'utils',
  'pages',
  'widgets',
  'router',
  'hooks',
};

const capabilityDependencies = <String, Set<String>>{
  'design_system': {},
  'adb': {},
  'scrcpy': {'adb'},
  'media_codec': {},
};

class _Package {
  _Package(this.name, this.directory, this.dependencies);
  final String name;
  final Directory directory;
  final Set<String> dependencies;
  String get lib => p.join(directory.path, 'lib');
}

/// 检查真实 import/export 图，生成的 part 不作为独立模块。
List<String> checkArchitecture(
  Directory root, {
  Map<String, Set<String>> allowedDependencies = capabilityDependencies,
}) {
  final manifest = loadYaml(
    File(p.join(root.path, 'pubspec.yaml')).readAsStringSync(),
  ) as YamlMap;
  final packages = <String, _Package>{};
  for (final path in manifest['workspace'] as YamlList) {
    final directory = Directory(p.join(root.path, path as String));
    final data = loadYaml(
      File(p.join(directory.path, 'pubspec.yaml')).readAsStringSync(),
    ) as YamlMap;
    final name = data['name'] as String;
    packages[name] = _Package(
      name,
      directory,
      (data['dependencies'] as YamlMap?)?.keys.cast<String>().toSet() ?? {},
    );
  }
  String relative(String path) => p.relative(path, from: root.path);
  final problems = <String>[];
  final application = packages['scrcpy_connect'];
  if (application != null) {
    problems.addAll(_checkApplicationBoundary(application.directory, relative));
  }
  final packageDirectory = Directory(p.join(root.path, 'packages'));
  if (packageDirectory.existsSync()) {
    for (final directory
        in packageDirectory.listSync().whereType<Directory>()) {
      if (File(p.join(directory.path, 'pubspec.yaml')).existsSync() &&
          !packages.values.any(
            (package) => p.equals(package.directory.path, directory.path),
          )) {
        problems.add('${relative(directory.path)}/pubspec.yaml: 未纳入工作区的本地包');
      }
    }
  }
  final graph = <String, Set<String>>{};
  for (final package in packages.values) {
    final allowed = allowedDependencies[package.name];
    if (allowed == null && package.name != 'scrcpy_connect') {
      problems.add(
        '${relative(package.directory.path)}/pubspec.yaml: 能力包缺少依赖层次声明',
      );
    }
    for (final dependency in package.dependencies.where(packages.containsKey)) {
      if (allowed != null && !allowed.contains(dependency)) {
        problems.add(
          '${relative(package.directory.path)}/pubspec.yaml: ${package.name} 不允许依赖 $dependency',
        );
      }
    }
    final lib = Directory(package.lib);
    if (!lib.existsSync()) continue;
    for (final file
        in lib
            .listSync(recursive: true, followLinks: false)
            .whereType<File>()) {
      if (!file.path.endsWith('.dart')) {
        continue;
      }
      final content = file.readAsStringSync();
      // FRB/Riverpod 的生成库由各自生成检查负责，不能要求手工改变其图形。
      if (content.startsWith('// This file is automatically generated') ||
          content.startsWith('// GENERATED CODE - DO NOT MODIFY BY HAND')) {
        continue;
      }
      if (package.name == 'scrcpy_connect') {
        final segments = p.split(p.relative(file.path, from: package.lib));
        if (segments.length > 1 &&
            !applicationLayers.contains(segments.first)) {
          problems.add('${relative(file.path)}: 应用顶层目录须按类型组织');
        }
      }
      final parsed = parseString(content: content, path: file.path);
      if (parsed.unit.directives.any(
        (directive) => directive is PartOfDirective,
      )) {
        continue;
      }
      final source = p.normalize(file.absolute.path);
      final edges = graph.putIfAbsent(source, () => {});
      for (final directive
          in parsed.unit.directives.whereType<UriBasedDirective>()) {
        if (directive is PartDirective) continue;
        final uris = [
          directive.uri.stringValue,
          if (directive is NamespaceDirective)
            ...directive.configurations.map(
              (configuration) => configuration.uri.stringValue,
            ),
        ];
        for (final literal in uris) {
          if (literal == null) continue;
          final uri = Uri.parse(literal);
          String? target;
          if (uri.scheme == 'package') {
            final segments = uri.pathSegments;
            if (segments.isEmpty) continue;
            final dependency = packages[segments.first];
            if (dependency == null) continue;
            if (dependency.name != package.name) {
              if (!package.dependencies.contains(dependency.name)) {
                problems.add(
                  '${relative(source)}: 未声明的直接依赖 ${dependency.name}',
                );
              }
              if (segments.length > 1 && segments[1] == 'src') {
                problems.add('${relative(source)}: 跨包访问私有实现 $literal');
              }
            }
            target = p.joinAll([dependency.lib, ...segments.skip(1)]);
          } else if (!uri.hasScheme) {
            target = File.fromUri(file.uri.resolveUri(uri)).path;
            if (!p.isWithin(package.lib, target)) {
              problems.add('${relative(source)}: 相对导入越过包的 lib 目录 $literal');
            }
          }
          if (target != null) {
            final normalized = p.normalize(p.absolute(target));
            // typed router 是组装入口，注册页及其加载适配器都会反向引用
            // 导航类型。业务层禁止依赖路由，另在此处明确检查，避免豁免掩盖倒置。
            final appLib = p.join(root.path, 'app', 'lib');
            if (package.name == 'scrcpy_connect' &&
                p.isWithin(appLib, source) &&
                p.isWithin(appLib, normalized)) {
              final fromLayer = p.split(p.relative(source, from: appLib)).first;
              final toLayer = p
                  .split(p.relative(normalized, from: appLib))
                  .first;
              if ({
                    'bootstrap',
                    'stores',
                    'services',
                    'models',
                    'utils',
                  }.contains(fromLayer) &&
                  {'pages', 'router', 'widgets', 'hooks'}.contains(toLayer)) {
                problems.add(
                  '${relative(source)}: 应用业务模块不得依赖界面或路由 ${relative(normalized)}',
                );
              } else if ((fromLayer == 'utils' && toLayer != 'utils') ||
                  (fromLayer == 'models' &&
                      !{'models', 'utils'}.contains(toLayer))) {
                problems.add(
                  '${relative(source)}: 工具与模型不得依赖业务实现 ${relative(normalized)}',
                );
              }
            }
            final routerRegistration =
                relative(source) ==
                    p.join('app', 'lib', 'router', 'app_router.dart') &&
                (p.isWithin(p.join(appLib, 'pages'), normalized) ||
                    normalized ==
                        p.join(appLib, 'router', 'route_resource_view.dart'));
            if (!routerRegistration) edges.add(normalized);
          }
        }
      }
    }
  }
  for (final cycle in _cycles(graph)) {
    problems.add('模块依赖环包含：${cycle.map(relative).join('，')}');
  }
  return problems..sort();
}

// 应用边界涵盖测试、hook 与平台目录；构建缓存不是源输入，不递归其受控依赖。
List<String> _checkApplicationBoundary(
  Directory application,
  String Function(String) relative,
) {
  final problems = <String>[];
  final manifest = File(p.join(application.path, 'pubspec.yaml'));
  final data = loadYaml(manifest.readAsStringSync()) as YamlMap;
  if (['dependencies', 'dev_dependencies', 'dependency_overrides'].any(
    (section) =>
        (data[section] as YamlMap?)?.containsKey('flutter_rust_bridge') ??
        false,
  )) {
    problems.add('${relative(manifest.path)}: 应用不得直接依赖 FRB');
  }
  // 只排除工具约定的确切路径，源码目录使用相同名称时仍须接受检查。
  final caches = {
    for (final segments in const [
      ['build'],
      ['.dart_tool'],
      ['android', '.gradle'],
      ['android', '.kotlin'],
      ['android', '.cxx'],
      ['android', 'app', '.cxx'],
      ['android', 'build'],
      ['android', 'app', 'build'],
      ['ios', 'Pods'],
      ['ios', '.symlinks'],
      ['ios', 'Flutter', 'ephemeral'],
      ['macos', 'Pods'],
      ['macos', '.symlinks'],
      ['macos', 'Flutter', 'ephemeral'],
      ['linux', 'flutter', 'ephemeral'],
      ['windows', 'flutter', 'ephemeral'],
    ])
      p.normalize(p.joinAll([application.path, ...segments])),
  };
  final pending = [application];
  while (pending.isNotEmpty) {
    for (final entry in pending.removeLast().listSync(followLinks: false)) {
      if (entry is Directory && !caches.contains(p.normalize(entry.path))) {
        pending.add(entry);
      } else if (entry is File) {
        final name = p.basename(entry.path);
        if (entry.path.endsWith('.rs')) {
          problems.add('${relative(entry.path)}: 应用不得包含 Rust 源码');
        } else if (RegExp(r'^flutter_rust_bridge(?:\..+)?\.ya?ml$')
            .hasMatch(name)) {
          problems.add('${relative(entry.path)}: FRB 配置必须位于工作区顶层');
        } else if (entry.path.endsWith('.dart')) {
          final source = entry.readAsStringSync();
          if (name.startsWith('frb_generated') ||
              RegExp(
                r'^// @generated by `flutter_rust_bridge`',
                multiLine: true,
              ).hasMatch(source)) {
            problems.add('${relative(entry.path)}: FRB 生成物必须由能力包维护');
          }
          // 生成声明、条件 import、export 和 part 都不能绕过应用边界。
          final unit = parseString(content: source, path: entry.path).unit;
          for (final directive
              in unit.directives.whereType<UriBasedDirective>()) {
            final uris = [
              directive.uri.stringValue,
              if (directive is NamespaceDirective)
                ...directive.configurations.map(
                  (entry) => entry.uri.stringValue,
                ),
            ];
            for (final literal in uris.whereType<String>()) {
              final uri = Uri.tryParse(literal);
              if (uri?.scheme == 'package' &&
                  uri!.pathSegments.firstOrNull == 'flutter_rust_bridge') {
                problems.add('${relative(entry.path)}: 应用不得直接导入 FRB $literal');
              }
            }
          }
        }
      }
    }
  }
  return problems;
}

// Tarjan 将同一依赖环仅报告一次，避免从每个入口重复输出。
List<List<String>> _cycles(Map<String, Set<String>> graph) {
  var sequence = 0;
  final indexes = <String, int>{}, low = <String, int>{};
  final stack = <String>[], active = <String>{};
  final cycles = <List<String>>[];
  void visit(String node) {
    indexes[node] = low[node] = sequence++;
    stack.add(node);
    active.add(node);
    for (final target in graph[node] ?? <String>{}) {
      if (!graph.containsKey(target)) continue;
      if (!indexes.containsKey(target)) {
        visit(target);
        if (low[target]! < low[node]!) low[node] = low[target]!;
      } else if (active.contains(target) && indexes[target]! < low[node]!) {
        low[node] = indexes[target]!;
      }
    }
    if (low[node] != indexes[node]) return;
    final group = <String>[];
    String member;
    do {
      member = stack.removeLast();
      active.remove(member);
      group.add(member);
    } while (member != node);
    if (group.length > 1 || (graph[node]?.contains(node) ?? false)) {
      cycles.add(group..sort());
    }
  }

  for (final node in graph.keys) {
    if (!indexes.containsKey(node)) visit(node);
  }
  return cycles;
}
