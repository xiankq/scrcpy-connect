#!/usr/bin/env python3
"""Generate the shared Dart/Rust command contract, or check it without writing."""

import argparse
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys


ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "protocol/commands.json"
RUST = ROOT / "crates/interop_bridge/src/commands_generated.rs"
DART = ROOT / "packages/interop_bridge/lib/src/protocol/commands_generated.dart"
FIELD_TYPES = {"string", "text", "integer", "number", "boolean", "object", "array"}


def load_schema(path=SCHEMA):
    schema = json.loads(path.read_text())
    if type(schema.get("version")) is not int or schema["version"] < 1:
        raise ValueError("protocol version must be a positive integer")
    commands = schema["commands"]
    names = [command["name"] for command in commands]
    if names != sorted(set(names)):
        raise ValueError("command names must be unique and sorted")
    for command in commands:
        if not re.fullmatch(r"[a-z]+(?:\.[a-zA-Z]+)+", command["name"]):
            raise ValueError(f"invalid command name: {command['name']}")
        if command["owner"] not in {"core", "bridge"}:
            raise ValueError(f"invalid command owner: {command['name']}")
        for group in ("required", "optional", "result"):
            fields = command.get(group, {})
            if not isinstance(fields, dict) or not set(fields.values()) <= FIELD_TYPES:
                raise ValueError(f"invalid {group} fields: {command['name']}")
        if set(command.get("required", {})) & set(command.get("optional", {})):
            raise ValueError(f"required/optional field overlap: {command['name']}")
    return schema


def names(command):
    parts = command["name"].split(".")
    pascal = "".join(part[0].upper() + part[1:] for part in parts)
    return pascal, pascal[0].lower() + pascal[1:]


def rust_source(schema):
    commands = [c for c in schema["commands"] if c["owner"] == "core"]
    lines = [
        "// Generated by tool/protocol_codegen.py; edit protocol/commands.json.",
        "use crate::protocol::{Field, FieldType};",
        f"pub(crate) const PROTOCOL_VERSION: u64 = {schema['version']};",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub(crate) enum Command {",
        *(f"{names(c)[0]}," for c in commands),
        "}",
        "impl Command {",
        "pub(crate) fn parse(value: &str) -> Option<Self> { Some(match value {",
        *(f'"{c["name"]}" => Self::{names(c)[0]},' for c in commands),
        "_ => return None, }) }",
        "pub(crate) fn as_str(self) -> &'static str { match self {",
        *(f'Self::{names(c)[0]} => "{c["name"]}",' for c in commands),
        "} }",
    ]
    for group in ("required", "optional", "result"):
        lines.append(f"pub(crate) fn {group}(self) -> &'static [Field] {{ match self {{")
        for c in commands:
            if c.get(group):
                fields = ",".join(
                    f'Field {{ name: "{name}", kind: FieldType::{kind.capitalize()} }}'
                    for name, kind in c[group].items()
                )
                lines.append(f"Self::{names(c)[0]} => &[{fields}],")
        lines.extend(["_ => &[],", "} }"])
    lines.append("}")
    return "\n".join(lines) + "\n"


def dart_source(schema):
    lines = [
        "// Generated by tool/protocol_codegen.py; edit protocol/commands.json.",
        f"const protocolVersion = {schema['version']};",
        "enum ProtocolFieldType { string, text, integer, number, boolean, object, array }",
        "enum InteropCommand {",
    ]
    for c in schema["commands"]:
        arguments = [json.dumps(c["name"])]
        if c["owner"] == "bridge":
            arguments.append("core: false")
        if c.get("requiresVerifiedState"):
            arguments.append("requiresVerifiedState: true")
        for group in ("required", "optional", "result"):
            if c.get(group):
                fields = ",".join(f"'{name}': ProtocolFieldType.{kind}" for name, kind in c[group].items())
                arguments.append(f"{group}: {{{fields}}}")
        lines.append(f"{names(c)[1]}({', '.join(arguments)}),")
    lines[-1] = lines[-1][:-1] + ";"
    lines.extend([
        "const InteropCommand(this.wire, {this.core = true, this.requiresVerifiedState = false,",
        "this.required = const {}, this.optional = const {}, this.result = const {}});",
        "final String wire;",
        "final bool core, requiresVerifiedState;",
        "final Map<String, ProtocolFieldType> required, optional, result;",
        "static final Map<String, InteropCommand> _byWire = {for (final command in values) command.wire: command};",
        "static InteropCommand? tryParse(String wire) => _byWire[wire];",
        "}",
    ])
    return "\n".join(lines) + "\n"


def formatted(source, language):
    if language == "rust":
        formatter = shutil.which("rustfmt") or str(Path.home() / ".cargo/bin/rustfmt")
        args = [formatter, "--edition", "2024", "--emit", "stdout"]
    else:
        args = ["dart", "format", "--output=show", "--summary=none"]
    return subprocess.run(args, input=source, text=True, capture_output=True, check=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schema = load_schema()
    outputs = {RUST: formatted(rust_source(schema), "rust"), DART: formatted(dart_source(schema), "dart")}
    stale = []
    for path, contents in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != contents:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(contents)
    if stale:
        print("Stale protocol outputs: " + ", ".join(stale), file=sys.stderr)
        print("Run python3 tool/protocol_codegen.py", file=sys.stderr)
        return 1
    print(f"Shared protocol {'checked' if args.check else 'generated'}: {len(schema['commands'])} commands")
    return 0


if __name__ == "__main__":
    sys.exit(main())
