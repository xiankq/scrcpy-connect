/// Generate the shared Dart/Rust command contract without resolving dependencies.
library;

import 'dart:convert';
import 'dart:io';

import 'package:args/args.dart';
import 'package:path/path.dart' as p;

import 'src/core_tooling.dart';

final root = repositoryRoot();
const fieldTypes = {
  'string',
  'text',
  'integer',
  'number',
  'boolean',
  'object',
  'array',
};

Map<String, dynamic> loadSchema([File? path]) {
  final schema = jsonDecode(
    (path ?? File(p.join(root.path, 'protocol/commands.json')))
        .readAsStringSync(),
  ) as Map<String, dynamic>;
  if (schema['version'] is! int || (schema['version'] as int) < 1) {
    throw const FormatException('protocol version must be a positive integer');
  }
  final commands = (schema['commands'] as List<dynamic>)
      .cast<Map<String, dynamic>>();
  final commandNames = commands.map((c) => c['name'] as String).toList();
  final sorted = commandNames.toSet().toList()..sort();
  if (jsonEncode(commandNames) != jsonEncode(sorted)) {
    throw const FormatException('command names must be unique and sorted');
  }
  for (final command in commands) {
    final name = command['name'] as String;
    if (!RegExp(r'^[a-z]+(?:\.[a-zA-Z]+)+$').hasMatch(name)) {
      throw FormatException('invalid command name: $name');
    }
    if (!{'core', 'bridge'}.contains(command['owner'])) {
      throw FormatException('invalid command owner: $name');
    }
    for (final group in ['required', 'optional', 'result', 'nativeResult']) {
      final fields = command[group] ?? <String, dynamic>{};
      if (fields is! Map<String, dynamic> ||
          !fields.values.every(fieldTypes.contains)) {
        throw FormatException('invalid $group fields: $name');
      }
    }
    if (fields(
      command,
      'required',
    ).keys.any(fields(command, 'optional').containsKey)) {
      throw FormatException('required/optional field overlap: $name');
    }
  }
  return schema;
}

Map<String, dynamic> fields(Map<String, dynamic> command, String group) =>
    command[group] as Map<String, dynamic>? ?? {};

(String, String) names(Map<String, dynamic> command) {
  final pascal = (command['name'] as String)
      .split('.')
      .map((part) => '${part[0].toUpperCase()}${part.substring(1)}')
      .join();
  return (pascal, '${pascal[0].toLowerCase()}${pascal.substring(1)}');
}

String rustSource(Map<String, dynamic> schema) {
  final commands = (schema['commands'] as List<dynamic>)
      .cast<Map<String, dynamic>>()
      .where((c) => c['owner'] == 'core')
      .toList();
  final lines = [
    // Keep this provenance line byte-compatible with the existing contract.
    '// Generated by tool/protocol_codegen.dart; edit protocol/commands.json.',
    'use crate::protocol::{Field, FieldType};',
    'pub(crate) const PROTOCOL_VERSION: u64 = ${schema['version']};',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub(crate) enum Command {',
    ...commands.map((c) => '${names(c).$1},'),
    '}', 'impl Command {',
    'pub(crate) fn parse(value: &str) -> Option<Self> { Some(match value {',
    ...commands.map((c) => '"${c['name']}" => Self::${names(c).$1},'),
    '_ => return None, }) }',
    "pub(crate) fn as_str(self) -> &'static str { match self {",
    ...commands.map((c) => 'Self::${names(c).$1} => "${c['name']}",'),
    '} }',
  ];
  for (final group in ['required', 'optional', 'result']) {
    lines.add("pub(crate) fn $group(self) -> &'static [Field] { match self {");
    for (final command in commands) {
      final selected = group == 'result' && command.containsKey('nativeResult')
          ? 'nativeResult'
          : group;
      if (fields(command, selected).isNotEmpty) {
        final values = fields(command, selected).entries
            .map((entry) {
              final kind = entry.value as String;
              return 'Field { name: "${entry.key}", kind: FieldType::${kind[0].toUpperCase()}${kind.substring(1)} }';
            })
            .join(',');
        lines.add('Self::${names(command).$1} => &[$values],');
      }
    }
    lines.addAll(['_ => &[],', '} }']);
  }
  lines.add('}');
  return '${lines.join('\n')}\n';
}

String dartSource(Map<String, dynamic> schema) {
  final lines = [
    '// Generated by tool/protocol_codegen.dart; edit protocol/commands.json.',
    'const protocolVersion = ${schema['version']};',
    'enum ProtocolFieldType { string, text, integer, number, boolean, object, array }',
    'enum InteropCommand {',
  ];
  for (final command
      in (schema['commands'] as List<dynamic>).cast<Map<String, dynamic>>()) {
    final arguments = [jsonEncode(command['name'])];
    if (command['owner'] == 'bridge') arguments.add('core: false');
    if (command['requiresVerifiedState'] == true) {
      arguments.add('requiresVerifiedState: true');
    }
    for (final group in ['required', 'optional', 'result']) {
      final values = fields(command, group);
      if (values.isNotEmpty) {
        arguments.add(
          '$group: {${values.entries.map((e) => "'${e.key}': ProtocolFieldType.${e.value}").join(',')}}',
        );
      }
    }
    lines.add('${names(command).$2}(${arguments.join(', ')}),');
  }
  lines[lines.length - 1] =
      '${lines.last.substring(0, lines.last.length - 1)};';
  lines.addAll([
    'const InteropCommand(this.wire, {this.core = true, this.requiresVerifiedState = false,',
    'this.required = const {}, this.optional = const {}, this.result = const {}});',
    'final String wire;',
    'final bool core, requiresVerifiedState;',
    'final Map<String, ProtocolFieldType> required, optional, result;',
    'static final Map<String, InteropCommand> _byWire = {for (final command in values) command.wire: command};',
    'static InteropCommand? tryParse(String wire) => _byWire[wire];',
    '}',
  ]);
  return '${lines.join('\n')}\n';
}

String formatted(String source, String language) {
  final work = Directory.systemTemp.createTempSync('protocol-format-');
  try {
    final input = File(
      p.join(work.path, language == 'rust' ? 'generated.rs' : 'generated.dart'),
    )..writeAsStringSync(source);
    final command = language == 'rust'
        ? [
            executable('rustfmt') ?? p.join(userHome, '.cargo/bin/rustfmt'),
            '--quiet',
            '--edition',
            '2024',
            '--emit',
            'stdout',
            input.path,
          ]
        : [
            dartExecutable,
            'format',
            '--output=show',
            '--summary=none',
            input.path,
          ];
    return runTool(command, quiet: true).stdout as String;
  } finally {
    work.deleteSync(recursive: true);
  }
}

void main(List<String> arguments) {
  try {
    final parser = ArgParser()
      ..addFlag('check', negatable: false)
      ..addFlag('help', abbr: 'h', negatable: false);
    final args = parser.parse(arguments);
    if (args['help'] as bool) {
      stdout.writeln(
        'Generate or check the shared Dart/Rust command contract.\n${parser.usage}',
      );
      return;
    }
    if (args.rest.isNotEmpty) {
      throw ArgumentError('Unexpected positional arguments');
    }
    final check = args['check'] as bool;
    final schema = loadSchema();
    final outputs = {
      'crates/interop_bridge/src/commands_generated.rs': formatted(
        rustSource(schema),
        'rust',
      ),
      'packages/device_protocol/lib/src/commands_generated.dart': formatted(
        dartSource(schema),
        'dart',
      ),
    };
    final stale = <String>[];
    for (final entry in outputs.entries) {
      final file = File(p.join(root.path, entry.key));
      if (check) {
        if (!file.existsSync() || file.readAsStringSync() != entry.value) {
          stale.add(entry.key);
        }
      } else {
        file.parent.createSync(recursive: true);
        file.writeAsStringSync(entry.value);
      }
    }
    if (stale.isNotEmpty) {
      stderr.writeln('Stale protocol outputs: ${stale.join(', ')}');
      stderr.writeln('Run dart tool/protocol_codegen.dart');
      exitCode = 1;
    } else {
      stdout.writeln(
        'Shared protocol ${check ? 'checked' : 'generated'}: ${(schema['commands'] as List<dynamic>).length} commands',
      );
    }
  } on Object catch (error) {
    stderr.writeln(error);
    exitCode = 1;
  }
}
